/**
 * The native messages of the phone app (wireless push steps, failures, the log) in the interface languages beyond
 * Chinese and English. Each message is written in the code as L.s("中文", "English") (or L.f(…, …, args) with {0}…
 * for values); the other languages come from native-texts.json, keyed by the English text:
 *
 *   node mobile/tools/native-texts.mjs           writes Tr.java (Android) and Tr.swift (iOS) from native-texts.json
 *   node mobile/tools/native-texts.mjs --check   fails when a message of the code has no entry (or an entry is unused,
 *                                                or a generated file is out of date)
 *   node mobile/tools/native-texts.mjs --list    prints the messages of the code (English, Chinese) as JSON
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MOBILE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const JAVA_DIR = join(MOBILE, 'android/app/src/main/java/io/github/maxwooow/grmod/push');
const SWIFT_DIR = join(MOBILE, 'ios-plugin/ios/Sources/GrCamera');
const JSON_FILE = join(MOBILE, 'native-texts.json');
/** The languages of native-texts.json, in the order of the generated tables. */
export const LANGS = ['zh-TW', 'ja', 'ko', 'es', 'de'];

/** The string literal starting at s[i] ('"'): [its text (escapes as written), the index after it]. */
function literal(s, i) {
  let j = i + 1, t = '';
  while (s[j] !== '"') { if (s[j] === '\\') { t += s[j] + s[j + 1]; j += 2; } else t += s[j++]; }
  return [t, j + 1];
}
/** String literals joined with + starting at s[i] ('"'): [the text, the index after the last one]. */
function literals(s, i) {
  let [t, j] = literal(s, i);
  for (let more = s.slice(j).match(/^\s*\+\s*"/); more; more = s.slice(j).match(/^\s*\+\s*"/)) {
    const [u, k] = literal(s, j + more[0].length - 1);
    t += u; j = k;
  }
  return [t, j];
}
/** The messages of one source file: every L.s / L.f call whose two first arguments are string literals. */
function messages(file) {
  const s = readFileSync(file, 'utf8'), out = [];
  for (const m of s.matchAll(/\bL\.[sf]\(\s*"/g)) {
    const [zh, after] = literals(s, m.index + m[0].length - 1);
    const rest = s.slice(after).match(/^\s*,\s*"/);
    if (!rest) throw new Error(`${file}: L.${m[0][2]} without two literals: ${s.slice(m.index, m.index + 120)}`);
    const [en] = literals(s, after + rest[0].length - 1);
    if (/\\\(/.test(zh + en)) throw new Error(`${file}: interpolation in a message (use L.f with {0}): ${en}`);
    out.push({ en, zh });
  }
  return out;
}
function codeMessages() {
  const all = new Map();
  for (const [dir, ext] of [[JAVA_DIR, '.java'], [SWIFT_DIR, '.swift']]) {
    for (const f of readdirSync(dir).filter((n) => n.endsWith(ext) && !/^Tr\./.test(n))) {
      for (const m of messages(join(dir, f))) if (!all.has(m.en)) all.set(m.en, m.zh);
    }
  }
  return all;
}
// Escapes: the keys are the English texts exactly as written in the code (Java and Swift share \" and \\).
const javaStr = (t) => `"${t.replace(/\\(?!["\\nt])/g, '\\\\').replace(/(?<!\\)"/g, '\\"')}"`;
function generate(table) {
  const keys = Object.keys(table).sort();
  const java = `// SPDX-License-Identifier: GPL-2.0-only
// Generated by mobile/tools/native-texts.mjs from mobile/native-texts.json: do not edit.
package io.github.maxwooow.grmod.push;

import java.util.HashMap;
import java.util.Map;

/** The native messages in ${LANGS.join(', ')}, keyed by their English text (L.java). */
final class Tr {
    private Tr() { }

    static final String[] LANGS = { ${LANGS.map((l) => `"${l}"`).join(', ')} };
    static final Map<String, String[]> MAP = new HashMap<>();

    static {
${keys.map((k) => `        MAP.put("${k}", new String[] { ${LANGS.map((l) => javaStr(table[k][l])).join(', ')} });`).join('\n')}
    }
}
`;
  const swift = `// SPDX-License-Identifier: GPL-2.0-only
// Generated by mobile/tools/native-texts.mjs from mobile/native-texts.json: do not edit.
import Foundation

/// The native messages in ${LANGS.join(', ')}, keyed by their English text (L.swift).
enum Tr {
    static let langs = [${LANGS.map((l) => `"${l}"`).join(', ')}]
    static let map: [String: [String]] = [
${keys.map((k) => `        "${k}": [${LANGS.map((l) => javaStr(table[k][l])).join(', ')}],`).join('\n')}
    ]
}
`;
  return { java, swift };
}

const cmd = process.argv[2];
const code = codeMessages();
if (cmd === '--list') {
  console.log(JSON.stringify([...code].map(([en, zh]) => ({ en, zh })), null, 1));
  process.exit(0);
}
const table = JSON.parse(readFileSync(JSON_FILE, 'utf8'));
const problems = [];
for (const en of code.keys()) {
  if (!table[en]) problems.push(`no entry: ${en}`);
  else for (const l of LANGS) if (typeof table[en][l] !== 'string' || !table[en][l]) problems.push(`no ${l}: ${en}`);
}
for (const en of Object.keys(table)) {
  if (!code.has(en)) problems.push(`unused entry: ${en}`);
  const vars = (t) => [...new Set(t.match(/\{\d\}/g) ?? [])].sort().join();
  for (const l of LANGS) if (table[en]?.[l] !== undefined && vars(table[en][l]) !== vars(en)) problems.push(`${l} variables differ: ${en}`);
}
const { java, swift } = generate(table);
if (cmd === '--check') {
  if (readFileSync(join(JAVA_DIR, 'Tr.java'), 'utf8') !== java) problems.push('Tr.java is out of date');
  if (readFileSync(join(SWIFT_DIR, 'Tr.swift'), 'utf8') !== swift) problems.push('Tr.swift is out of date');
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  console.log(`native texts: ${code.size} messages in ${LANGS.length} more languages`);
} else {
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
  writeFileSync(join(JAVA_DIR, 'Tr.java'), java);
  writeFileSync(join(SWIFT_DIR, 'Tr.swift'), swift);
  console.log(`wrote Tr.java and Tr.swift: ${code.size} messages`);
}
