"""Compile tools/adjslots/adjslots.c and write core/src/fw/aspect/adjslots-code.ts.

Position independent (-fropi -frwpi, no global data), linked at two addresses and compared, as the
date imprint module (tools/datestamp/gen.py). Soft float, cortex-a9, ARM, -Os, no library. The
module has several entry points; their offsets are written next to the code.
Compiler: clang if present, else `python3 -m ziglang cc` (GRMOD_ZIG=1 forces it).
"""
import base64
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = HERE / 'adjslots.c'
OUT = ROOT / 'core' / 'src' / 'fw' / 'aspect' / 'adjslots-code.ts'
ENTRIES = ['adj_slot_function', 'adj_can_open', 'adj_draw_more', 'adj_touchable_more', 'adj_taps_more', 'adj_bind',
           'adj_get_position', 'adj_set_position']
USE_ZIG = bool(os.environ.get('GRMOD_ZIG')) or not (shutil.which('clang') and shutil.which('ld.lld') and shutil.which('llvm-objcopy'))
FLAGS = ['-mcpu=cortex_a9' if USE_ZIG else '-mcpu=cortex-a9', '-marm', '-mfloat-abi=soft', '-Os',
         '-ffreestanding', '-fno-builtin', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-nostdlib',
         '-fropi', '-frwpi', '-fno-jump-tables', '-Wall', '-Wextra', '-Werror']


def tools():
    if not USE_ZIG:
        return ['clang', '-target', 'armv7-none-eabi'], ['ld.lld'], ['llvm-objcopy']
    z = [sys.executable, '-m', 'ziglang']
    return z + ['cc', '-target', 'arm-freestanding-eabi'], z + ['ld.lld'], z + ['objcopy']


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'{" ".join(map(str, cmd))}\n{r.stdout}{r.stderr}')
    return r.stdout


def build(cc, ld, objcopy, tmp, origin):
    obj = tmp / 'adj.o'
    run(cc + FLAGS + ['-c', SRC, '-o', obj])
    undefined = [l.split()[-1] for l in run(['readelf', '-s', '-W', obj]).splitlines() if ' UND ' in l and len(l.split()) >= 8]
    if undefined:
        sys.exit(f'module needs symbols from a library: {undefined}')
    elf = tmp / f'adj_{origin:x}.elf'
    run(ld + [f'-Ttext=0x{origin:x}', f'--entry={ENTRIES[0]}', '-o', elf, obj])
    out = tmp / f'adj_{origin:x}.bin'
    run(objcopy + ['-O', 'binary', '-j', '.text', elf, out])
    sections = run(['readelf', '-S', '-W', elf])
    for name in ('.data', '.bss', '.rodata', '.got'):
        if f' {name} ' in sections or f' {name}.' in sections:
            sys.exit(f'module has a {name} section')
    symbols = run(['readelf', '-s', '-W', elf]).splitlines()
    offsets = {}
    for name in ENTRIES:
        line = [l for l in symbols if l.strip().endswith(f' {name}')]
        if not line:
            sys.exit(f'no {name}')
        offsets[name] = int(line[0].split()[1], 16) - origin
    return out.read_bytes(), offsets


def main():
    cc, ld, objcopy = tools()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        a, ea = build(cc, ld, objcopy, tmp, 0x10000)
        b, eb = build(cc, ld, objcopy, tmp, 0x543f0000)
    if a != b or ea != eb:
        sys.exit('module is not position independent')
    while len(a) % 4:
        a += b'\0'
    version = run(cc + ['--version']).splitlines()[0]
    src_hash = hashlib.sha256(SRC.read_bytes()).hexdigest()
    entries = ', '.join(f'{k[4:]}: {v}' for k, v in ea.items())
    OUT.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/adjslots/gen.py from tools/adjslots/adjslots.c -- do not edit.\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256: {src_hash}\n'
        '// Position independent, soft-float ABI; entry offsets below.\n\n'
        f"export const ADJSLOTS_CODE = '{base64.b64encode(a).decode()}';\n"
        f'export const ADJSLOTS_CODE_LENGTH = {len(a)};\n'
        f'export const ADJSLOTS_ENTRY = {{ {entries} }} as const;\n'
        f"export const ADJSLOTS_SOURCE_SHA256 = '{src_hash}';\n")
    print(f'{OUT}: {len(a)} bytes, entries {ea}')


if __name__ == '__main__':
    main()
