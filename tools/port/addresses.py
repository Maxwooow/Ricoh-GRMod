"""Write a release's address table (core/src/fw/<release>/addresses.ts) from its address map.

    python3 tools/port/addresses.py            # every table
    python3 tools/port/addresses.py --check    # fail when a committed table is not what the map gives

The table is what `adr()` of the release's target module looks addresses up in (core/src/fw/release.ts):
every address of the program's own release that the map resolved, with its address in this release.
An address the map could not resolve is left out, so that using it stops the program instead of
carrying it over.
"""
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
# table file -> the maps that lead from the program's own release to this one, in order
TABLES = {
    'core/src/fw/gr4v121/addresses.ts': ('GR IV 1.20 (the program in fw/gr4v120)', 'GR IV 1.21', ['tools/port/gr4-121-map.json']),
    'core/src/fw/gr3x170/addresses.ts': ('GR IIIx 1.60 / GR III 2.10 (the program in fw/gr3x)', 'GR IIIx 1.70 / GR III 2.20', ['tools/port/gr3-p2-map.json']),
    'core/src/fw/gr3x171/addresses.ts': ('GR IIIx 1.60 / GR III 2.10 (the program in fw/gr3x)', 'GR IIIx 1.71 / GR III 2.21', ['tools/port/gr3-p2-map.json', 'tools/port/gr3-p3-map.json']),
}


def table(maps):
    chain = None
    for m in maps:
        step = {int(k, 16): int(e['new'], 16) for k, e in json.loads((REPO / m).read_text())['addresses'].items() if e.get('ok') and e.get('new')}
        chain = step if chain is None else {a: step[b] for a, b in chain.items() if b in step}
    return chain


def text(src, dst, maps):
    t = table(maps)
    rows = [f'  [0x{a:08x}, 0x{b:08x}],' for a, b in sorted(t.items())]
    return ('// GENERATED by tools/port/addresses.py from ' + ', '.join(maps) + ' -- do not edit.\n'
            f'/** {src} -> {dst}: {len(t)} addresses. */\n'
            'export const ADDRESSES: ReadonlyMap<number, number> = new Map([\n' + '\n'.join(rows) + '\n]);\n')


def main():
    check = '--check' in sys.argv[1:]
    bad = []
    for path, (src, dst, maps) in TABLES.items():
        want = text(src, dst, maps)
        p = REPO / path
        if check:
            if not p.exists() or p.read_text() != want: bad.append(path)
        else:
            p.parent.mkdir(parents=True, exist_ok=True); p.write_text(want); print('wrote', path)
    if bad: sys.exit('not what the address map gives (run python3 tools/port/addresses.py): ' + ', '.join(bad))
    if check: print('address tables: ok')


if __name__ == '__main__':
    main()
