"""Writes core/src/color/photo-samples.ts: pixel colours of the Kodak Lossless True Color Image Suite
(kodim01..24, 768 x 512, released by Kodak for unrestricted use), for the .cube import option `photoFit`.

Each picture is reduced 4x by box averaging (192 x 128). From the odd-numbered pictures (kodim01, 03, ...)
4096 pixels are drawn for the fit; from the even-numbered ones another 4096 for choosing between candidate
fits. Colours are stored as 8-bit sRGB, as the camera's Standard JPEG holds them.

Usage: make_samples.py <folder with kodim01.png .. kodim24.png> [out.ts]
       make_samples.py --f64 <24 x 24576 x 3 float64 file, the same reduction already done> [out.ts]
"""
import base64, os, sys
import numpy as np

N = 4096
SEED = 12345

def load(args):
    if args[0] == '--f64':
        return np.fromfile(args[1], dtype='<f8').reshape(24, -1, 3), args[2:]
    from PIL import Image
    imgs = []
    for i in range(1, 25):
        a = np.asarray(Image.open(os.path.join(args[0], f'kodim{i:02d}.png')).convert('RGB'), dtype=np.float64) / 255
        if a.shape[0] > a.shape[1]: a = a.transpose(1, 0, 2)          # the portrait pictures, turned
        a = a.reshape(128, 4, 192, 4, 3).mean(axis=(1, 3))
        imgs.append(np.round(a * 255) / 255)
    return np.stack(imgs).reshape(24, -1, 3), args[1:]

def draw(k, pictures, rng):
    pic = rng.choice(pictures, N)
    px = rng.integers(0, k.shape[1], N)
    return np.clip(np.round(k[pic, px] * 255), 0, 255).astype(np.uint8)

def main():
    k, rest = load(sys.argv[1:])
    out = rest[0] if rest else os.path.join(os.path.dirname(__file__), '..', '..', 'core', 'src', 'color', 'photo-samples.ts')
    rng = np.random.default_rng(SEED)
    fit = draw(k, np.arange(0, 24, 2), rng)    # kodim01, 03, ... (0-based even)
    check = draw(k, np.arange(1, 24, 2), rng)  # kodim02, 04, ...
    b64 = lambda a: base64.b64encode(a.tobytes()).decode()
    wrap = lambda s: '\n'.join("  '" + s[i:i + 100] + "' +" for i in range(0, len(s), 100))[:-2]
    with open(out, 'w') as f:
        f.write('// SPDX-License-Identifier: GPL-2.0-only\n')
        f.write('// GENERATED by tools/photo-fit/make_samples.py -- do not edit.\n')
        f.write('// Pixel colours of the Kodak Lossless True Color Image Suite (released by Kodak for unrestricted use),\n')
        f.write(f'// {N} RGB triples each, 8-bit sRGB, base64. FIT: odd-numbered pictures; CHECK: even-numbered pictures.\n\n')
        f.write(f'export const PHOTO_FIT_B64 =\n{wrap(b64(fit))};\n\n')
        f.write(f'export const PHOTO_CHECK_B64 =\n{wrap(b64(check))};\n')
    print('wrote', out)

if __name__ == '__main__':
    main()
