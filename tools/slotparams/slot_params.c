/* Own adjustment parameters for the added Image Control slots (styles 34, ...).
 *
 * The firmware keeps the parameters (saturation, hue, contrast, ...) per factory style in the
 * user settings record, and the added styles use Cinema Yellow's (18) fields: everything that
 * reads them for the selected style (the live-view generator, development) is patched to take
 * the added styles as 18. So for each photo/movie custom set (8 combinations) Cinema Yellow's
 * fields belong to one "owner": the added style selected in that set, or else Cinema Yellow.
 * The other owners' values wait in a table here, saved as its own record (HTData 12):
 *   - a getter or setter for the owner goes to the fields (the firmware as it is);
 *   - for any other owner it goes to the table;
 *   - when a set's style changes owner, the old owner's values move from the fields to the
 *     table and the new owner's values are set through the firmware's own setters.
 * The fields are always the selected look's values, in the record the firmware saves, so the
 * record and the table cannot disagree about the look in use (a lost table write only loses
 * changes to looks that were not selected).
 *
 * Developed and tested as GR Mod test firmwares 026..034 on a GR IV HDF (four slots). The entry
 * hooks (sp_*_stub_*) are generated by gen_slotparams.py.
 */
#include <stdint.h>

#ifndef SLOT_COUNT
#error SLOT_COUNT (1..12) is set by gen_slotparams.py
#endif
#define CY 18u
#define FIRST 34u
/* Cinema Yellow and the added slots. Counts 1..6 keep the original table size (7 owners) so
 * firmwares built before 12 slots were possible read and write their record unchanged. */
#define OWNERS (SLOT_COUNT < 6u ? 7u : 1u + SLOT_COUNT)
#define COMBOS 8u                 /* photo sets 0..3, movie sets 0..3 */
#define NP 13u
#define REC_ID 12u
#define REC_MAGIC 0x32505247u     /* 'GRP2' (test 027's 'GRP1' tables were built from an empty record) */
#define REC_VERSION 2u            /* 1: tests 028..033 */
#define STATE_MAGIC 0x50534c54u
#define TBYTES (OWNERS * COMBOS * NP)
#define REC_WORDS (3u + TBYTES / 4u + 1u)

extern uint8_t *storage_singleton(void);
extern uint32_t store_write(void *store, uint32_t id, uint32_t size, const void *data);
extern uint32_t store_read(void *store, uint32_t id, uint32_t size, void *data);
extern uint32_t store_size(void *store, uint32_t id);
extern void *heap_alloc(uint32_t size);
extern uint32_t prior_native_save(uint8_t *mode);
extern uint32_t prior_native_load(uint8_t *mode, uint8_t *current, void *a2, void *a3);
extern volatile uint32_t sp_gap[];       /* zeroed at every start; [0] = state */
extern uint8_t settings_object[];        /* 0x55084DD8: the record the setters write is at +4 */

/* Offsets in the settings object of Cinema Yellow's fields, per parameter and combination
 * (0 = none: four parameters exist for photos only). The setters write these. */
static const uint16_t FIELD[NP][COMBOS] = {
    {0x15b, 0x207, 0x2b3, 0x35f, 0x51d, 0x599, 0x615, 0x691},
    {0x165, 0x211, 0x2bd, 0x369, 0x526, 0x5a2, 0x61e, 0x69a},
    {0x173, 0x21f, 0x2cb, 0x377, 0x532, 0x5ae, 0x62a, 0x6a6},
    {0x180, 0x22c, 0x2d8, 0x384, 0x53e, 0x5ba, 0x636, 0x6b2},
    {0x18d, 0x239, 0x2e5, 0x391, 0x54a, 0x5c6, 0x642, 0x6be},
    {0x19a, 0x246, 0x2f2, 0x39e, 0x556, 0x5d2, 0x64e, 0x6ca},
    {0x1a7, 0x253, 0x2ff, 0x3ab, 0x562, 0x5de, 0x65a, 0x6d6},
    {0x1b0, 0x25c, 0x308, 0x3b4, 0x56a, 0x5e6, 0x662, 0x6de},
    {0x1d8, 0x284, 0x330, 0x3dc, 0x58f, 0x60b, 0x687, 0x703},
    {0x1e4, 0x290, 0x33c, 0x3e8, 0, 0, 0, 0},
    {0x1fb, 0x2a7, 0x353, 0x3ff, 0, 0, 0, 0},
    {0x1fc, 0x2a8, 0x354, 0x400, 0, 0, 0, 0},
    {0x1fd, 0x2a9, 0x355, 0x401, 0, 0, 0, 0},
};

/* Factory values of Cinema Yellow's fields (UserDataInitValue, the same in every set). */
static const uint8_t FACTORY[NP] = {4, 4, 3, 7, 4, 2, 1, 1, 4, 4, 0, 1, 1};

/* Neutral values ("0" on the parameter screen) the added slots start from and show as their
 * default: the middle of the -4..+4 scales, parameter 8 off (Standard's value), grain off with
 * Cinema Yellow's strength and size (they have no neutral position). */
static const uint8_t NEUTRAL[NP] = {4, 4, 4, 4, 4, 4, 4, 0, 4, 4, 0, 1, 1};

/* Entry of each parameter's setter (parameters 0..6, 8, 17..21 of the 23). */
static const uint32_t native_setters[NP] = {
    0x533ad4e0, 0x533adce0, 0x533ae4e0, 0x533af100, 0x533afd20, 0x533b0940, 0x533b1560,
    0x533b28e0, 0x533b3fbc, 0x533b4bdc, 0x533b51c0, 0x533b5704, 0x533b5c48,
};

/* Entry of each parameter's getter. */
static const uint32_t native_getters[NP] = {
    0x533b7130, 0x533b7818, 0x533b7f00, 0x533b8928, 0x533b9350, 0x533b9d78, 0x533ba7a0,
    0x533bb858, 0x533bcdb8, 0x533bd7e0, 0x533bdcf0, 0x533be188, 0x533be620,
};

/* In-camera RAW development (RawDevelopmentModel): per custom base (0..3, the photo sets) and
 * look it keeps 18 bytes of parameters and two of grain; the added looks are patched to use
 * Cinema Yellow's (look 9). Like the settings fields, those bytes belong to one owner per base,
 * the others' values wait here (see sp_raw_*). */
#define RAW_BASES 4u
#define RAW_CY 9u
#define RAW_FIRST 21u
#define RAW_LOOK 0x9du            /* + base: the base's look */
#define RAW_ROWS 0xa1u            /* + base * 0x17a + look * 0x12: 18 bytes */
#define RAW_BASE_STRIDE 0x17au
#define RAW_ROW 0x12u
#define RAW_GRAIN 0x71au          /* + (base * 21 + look) * 2: strength, size */
#define RAW_VALUES (RAW_ROW + 2u)

typedef struct {
    uint8_t *model;
    uint8_t own[RAW_BASES];
    uint8_t v[RAW_BASES][OWNERS][RAW_VALUES];
} Raw;

typedef struct {
    uint32_t magic, loaded, dirty, last_write;
    uint8_t t[OWNERS][COMBOS][NP];
    uint32_t rec[REC_WORDS];
    Raw raw;
} State;

static State *state(void) {
    State *s = (State *)sp_gap[0];
    return s && s->magic == STATE_MAGIC ? s : 0;
}

static void *ht_store(void) {
    uint8_t *s = storage_singleton();
    return s ? *(void **)(s + 0x14) : 0;
}

static int combo(uint32_t mode, uint32_t set) {
    return mode <= 1 && set <= 3 ? (int)(mode * 4 + set) : -1;
}

/* The style of a set, from the record the setters write. */
static uint32_t style_of(int c) {
    return settings_object[c < 4 ? 0x153 + c : 0x515 + (c - 4)];
}

/* Owner index of a style: Cinema Yellow 0, added slot k k+1, anything else -1. */
static int owner_of(uint32_t style) {
    if (style == CY) return 0;
    if (style >= FIRST && style < FIRST + SLOT_COUNT) return (int)(style - FIRST + 1);
    return -1;
}

static int owner(int c) {
    int o = owner_of(style_of(c));
    return o < 0 ? 0 : o;
}

/* Calls a native setter past its entry hook: `mov ip,sp` then the rest of it. */
__attribute__((naked)) static uint32_t native_set(uint32_t value, uint32_t mode, uint32_t set, uint32_t style, uint32_t entry) {
    __asm__ volatile(
        "push {r4, lr}\n"
        "ldr r4, [sp, #8]\n"
        "sub sp, sp, #8\n"
        "str r0, [sp]\n"
        "mov r0, #0\n"
        "add r4, r4, #4\n"
        "mov ip, sp\n"
        "blx r4\n"
        "add sp, sp, #8\n"
        "pop {r4, pc}\n");
}

/* Calls a native getter past its entry hook. */
__attribute__((naked)) static uint32_t native_get(uint32_t mode, uint32_t set, uint32_t style, uint32_t entry) {
    __asm__ volatile(
        "push {r4, lr}\n"
        "add r4, r3, #4\n"
        "mov r3, r2\n"
        "mov r2, r1\n"
        "mov r1, r0\n"
        "mov r0, #0\n"
        "mov ip, sp\n"
        "blx r4\n"
        "pop {r4, pc}\n");
}

/* Calls a style wrapper past its entry hook. */
__attribute__((naked)) static uint32_t native_wrapper(void *obj, uint32_t style, uint32_t entry) {
    __asm__ volatile(
        "add r2, r2, #4\n"
        "mov ip, sp\n"
        "bx r2\n");
}


/* ---- getters and setters --------------------------------------------------------------- */
#define HANDLED 0x80000000u

/* j: parameter position (0..12). Returns the value: from the table for a look that does not
 * own the fields, otherwise from the firmware's getter (with Cinema Yellow for an added look). */
static uint32_t route_get(uint32_t j, uint32_t mode, uint32_t set, uint32_t style) {
    int si = owner_of(style);
    if (si < 0) return native_get(mode, set, style, native_getters[j]);
    int c = combo(mode, set);
    if (c < 0 || j >= NP || FIELD[j][c] == 0) return native_get(mode, set, CY, native_getters[j]);
    State *s = state();
    if (!s || !s->loaded || si == owner(c)) return native_get(mode, set, CY, native_getters[j]);
    return s->t[si][c][j];
}

uint32_t sp_get(uint32_t j, uint32_t mode, uint32_t set, uint32_t style) {
    return route_get(j, mode, set, style);
}

uint32_t sp_route_set(uint32_t j, uint32_t mode, uint32_t set, uint32_t style, uint32_t value) {
    int si = owner_of(style);
    if (si < 0) return style;
    int c = combo(mode, set);
    if (c < 0 || j >= NP || FIELD[j][c] == 0) return CY;
    State *s = state();
    if (!s || !s->loaded || si == owner(c)) return CY;
    if (s->t[si][c][j] != (uint8_t)value) { s->t[si][c][j] = (uint8_t)value; s->dirty = 1; }
    return HANDLED;
}

/* ---- style changes ------------------------------------------------------------------------ */
static void move_owner(State *s, int c, int from, int to) {
    uint32_t mode = (uint32_t)c >> 2, set = (uint32_t)c & 3;
    for (uint32_t j = 0; j < NP; j++)
        if (FIELD[j][c]) s->t[from][c][j] = settings_object[FIELD[j][c]];
    for (uint32_t j = 0; j < NP; j++)
        if (FIELD[j][c]) native_set(s->t[to][c][j], mode, set, CY, native_setters[j]);
    s->dirty = 1;
}

/* Hook of the firmware's "style of set c" setter (photo 0x532B6F80..., movie 0x53300AA0...). */
uint32_t sp_style_set(void *obj, uint32_t style, uint32_t c, uint32_t entry) {
    uint32_t before = style_of((int)c);
    uint32_t r = native_wrapper(obj, style, entry);
    State *s = state();
    if (s && s->loaded) {
        int from = owner_of(before), to = owner(c);
        if (from < 0) from = 0;
        if (from != to) move_owner(s, (int)c, from, to);
    }
    return r;
}

/* ---- RAW development ------------------------------------------------------------------- */
/* Where parameter j sits in a look's 18 bytes (11..12: the two grain bytes, after them). */
static const uint8_t RAW_POS[NP] = {0, 1, 2, 3, 4, 5, 6, 8, 14, 15, 16, RAW_ROW, RAW_ROW + 1};

static int raw_owner(uint32_t look) {
    if (look == RAW_CY) return 0;
    if (look >= RAW_FIRST && look < RAW_FIRST + SLOT_COUNT) return (int)(look - RAW_FIRST + 1);
    return -1;
}

/* Cinema Yellow's bytes of a base: its row and its grain pair. */
static volatile uint8_t *raw_row(uint8_t *m, uint32_t b) { return m + RAW_ROWS + b * RAW_BASE_STRIDE + RAW_CY * RAW_ROW; }
static volatile uint8_t *raw_grain(uint8_t *m, uint32_t b) { return m + RAW_GRAIN + (b * 21u + RAW_CY) * 2u; }

static void raw_save(State *s, uint32_t b, int o) {
    volatile uint8_t *row = raw_row(s->raw.model, b), *g = raw_grain(s->raw.model, b);
    volatile uint8_t *v = s->raw.v[b][o];
    for (uint32_t i = 0; i < RAW_ROW; i++) v[i] = row[i];
    v[RAW_ROW] = g[0]; v[RAW_ROW + 1] = g[1];
}

static void raw_restore(State *s, uint32_t b, int o) {
    volatile uint8_t *row = raw_row(s->raw.model, b), *g = raw_grain(s->raw.model, b);
    volatile uint8_t *v = s->raw.v[b][o];
    for (uint32_t i = 0; i < RAW_ROW; i++) row[i] = v[i];
    g[0] = v[RAW_ROW]; g[1] = v[RAW_ROW + 1];
}

/* After the model has filled every look from the settings (opening a RAW file): Cinema Yellow's
 * bytes of base b hold the values of the look that owns the settings fields of photo set b; every
 * other owner gets its own saved values (the same the shooting uses). */
void sp_raw_init(uint8_t *model) {
    State *s = state();
    if (!s || !s->loaded || !model) return;
    s->raw.model = model;
    for (uint32_t b = 0; b < RAW_BASES; b++) {
        int own = owner((int)b);
        s->raw.own[b] = (uint8_t)own;
        for (int o = 0; o < (int)OWNERS && o <= SLOT_COUNT; o++) {
            if (o == own) continue;
            volatile uint8_t *v = s->raw.v[b][o];
            for (uint32_t i = 0; i < RAW_VALUES; i++) v[i] = 0;
            uint32_t style = o == 0 ? CY : FIRST + (uint32_t)o - 1;
            for (uint32_t j = 0; j < NP; j++) v[RAW_POS[j]] = (uint8_t)route_get(j, 0, b, style);
        }
    }
}

/* Cinema Yellow's bytes of base b now belong to `look` (Cinema Yellow or an added look). */
void sp_raw_own(uint8_t *model, uint32_t b, uint32_t look) {
    State *s = state();
    int o = raw_owner(look);
    if (!s || !s->loaded || !model || model != s->raw.model || b >= RAW_BASES || o < 0) return;
    if (s->raw.own[b] == (uint8_t)o) return;
    raw_save(s, b, s->raw.own[b]);
    raw_restore(s, b, o);
    s->raw.own[b] = (uint8_t)o;
}

/* Before the model applies a base's look (every change of look goes through it). */
void sp_raw_sync(uint8_t *model) {
    for (uint32_t b = 0; b < RAW_BASES; b++) sp_raw_own(model, b, model ? model[RAW_LOOK + b] : 0);
}

/* ---- the record --------------------------------------------------------------------------- */
static uint32_t checksum(const uint32_t *w, uint32_t n) {
    uint32_t sum = 0x6a09e667u;
    for (uint32_t i = 0; i < n; i++) sum = (sum ^ w[i]) * 0x01000193u + i;
    return sum;
}

static void copy_bytes(uint8_t *d, const uint8_t *src, uint32_t n) {
    for (uint32_t i = 0; i < n; i++) ((volatile uint8_t *)d)[i] = src[i];
}

#define OLD_MAGIC 0x31505247u     /* 'GRP1', test 027 */

/* 1: valid table read; 0: none; 2: test 027's table (its sets may have been emptied);
 * 3: a table of tests 028..033 (version 1), where the added slots started from Cinema Yellow's
 * values: Cinema Yellow's values are kept, the added slots start again from neutral (034). */
static int read_record(State *s) {
    void *st = ht_store();
    if (!st) return 0;
    if (store_size(st, REC_ID) != REC_WORDS * 4) return 0;
    if (!store_read(st, REC_ID, REC_WORDS * 4, s->rec)) return 0;
    if (s->rec[0] == OLD_MAGIC) return 2;
    if (s->rec[0] != REC_MAGIC || (s->rec[1] != 1 && s->rec[1] != REC_VERSION) || s->rec[2] != TBYTES) return 0;
    if (s->rec[REC_WORDS - 1] != checksum(s->rec, REC_WORDS - 1)) return 0;
    copy_bytes(&s->t[0][0][0], (const uint8_t *)&s->rec[3], TBYTES);
    return s->rec[1] == REC_VERSION ? 1 : 3;
}

static void write_record(State *s) {
    void *st = ht_store();
    if (!st) return;
    s->rec[0] = REC_MAGIC; s->rec[1] = REC_VERSION; s->rec[2] = TBYTES;
    copy_bytes((uint8_t *)&s->rec[3], &s->t[0][0][0], TBYTES);
    s->rec[REC_WORDS - 1] = checksum(s->rec, REC_WORDS - 1);
    s->last_write = store_write(st, REC_ID, REC_WORDS * 4, s->rec) ? 1 : 2;
    if (s->last_write == 1) s->dirty = 0;
}

/* Settings load: the first one (at start) loads the table. `current` is the record just read
 * (laid out from its first byte, the settings object's copy starts 4 bytes in); it becomes the
 * settings object's record only after this returns. Without a valid table Cinema Yellow keeps the
 * values in that record's Cinema Yellow fields and the added slots start neutral.
 * Repair after test 027, which set looks to an empty table: a set with all its fields 0, or with
 * six or more at 0 when 027's table is there (the factory values have one), gets the factory
 * values back. */
uint32_t sp_load(uint8_t *mode, uint8_t *current, void *a2, void *a3) {
    uint32_t r = prior_native_load(mode, current, a2, a3);
    if (state() || !current) return r;
    State *s = (State *)heap_alloc(sizeof(State));
    if (!s) return r;
    for (uint32_t i = 0; i < sizeof(State) / 4; i++) ((volatile uint32_t *)s)[i] = 0;
    int found = read_record(s);
    for (uint32_t c = 0; c < COMBOS; c++) {
        uint32_t zeros = 0, n = 0;
        for (uint32_t j = 0; j < NP; j++) if (FIELD[j][c]) { n++; if (!current[FIELD[j][c] - 4]) zeros++; }
        if (zeros == n || (found == 2 && zeros >= 6))
            for (uint32_t j = 0; j < NP; j++) if (FIELD[j][c]) current[FIELD[j][c] - 4] = FACTORY[j];
    }
    if (found != 1) {
        /* Cinema Yellow keeps its values (the record's, or the old table's); the added slots
         * start neutral. A set that has an added slot selected holds that slot's values in the
         * record (Cinema Yellow's are in the table), so those fields are set neutral as well. */
        for (uint32_t c = 0; c < COMBOS; c++) {
            int own = owner_of(current[(c < 4 ? 0x153 + c : 0x515 + (c - 4)) - 4]);
            for (uint32_t j = 0; j < NP; j++) {
                uint32_t f = FIELD[j][c];
                if (found != 3) s->t[0][c][j] = f ? current[f - 4] : 0;
                for (uint32_t o = 1; o < OWNERS; o++) s->t[o][c][j] = f ? NEUTRAL[j] : 0;
                if (f && own > 0) current[f - 4] = NEUTRAL[j];
            }
        }
        s->dirty = 1;
    }
    s->loaded = 1;
    s->magic = STATE_MAGIC;
    sp_gap[0] = (uint32_t)s;
    return r;
}

/* Settings save (at power off): then the table, if it changed. */
uint32_t sp_save(uint8_t *mode) {
    uint32_t r = prior_native_save(mode);
    State *s = state();
    if (s && s->loaded && s->dirty) write_record(s);
    return r;
}
