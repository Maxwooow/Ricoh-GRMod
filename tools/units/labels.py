"""The feet / inch labels of the GR IV's manual focus scale (development tool).

    python3 tools/units/labels.py FONT [--sheet out.png]

Writes core/src/fw/gr4v120/aspect/units-icons.ts: 30 x 20 icons in the style of the camera's own scale labels
(icons 0x2c0 "0.3", 0x2c3 "m", 0x8e "1", ...): white figures with a 1-pixel black outline on a transparent tile,
smoothed edges blended towards the outline (grey levels), every outlined pixel opaque.

FONT is Barlow Semi Condensed SemiBold (SIL Open Font License), e.g. the file
`files/barlow-semi-condensed-latin-600-normal.woff` of the npm package @fontsource/barlow-semi-condensed@5.1.0:
the camera's own font is in a format of its own; this one is close to it in width and weight. The icons are
generated once and committed; the program does not need the font.

Each icon is stored as 600 bytes, one per pixel row by row: 0 transparent, else 1 + the grey level (0..254;
255 is written as 254), opaque.
"""
import argparse, base64, sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / 'core' / 'src' / 'fw' / 'gr4v120' / 'aspect' / 'units-icons.ts'
W, H, SS = 30, 20, 8

# name -> (text, figure height (the digit 0) in pixels, baseline row, centred)
# Figures as the camera's: 18 pixels high, rows 1..18, from the left edge. Units as its "m" / "cm": baseline row 16, centred.
LABELS = {
    'ft': ('ft', 15, 16, True), 'in': ('in', 15, 16, True),
    '16': ('16', 18, 18, False), '9.8': ('9.8', 18, 18, False), '3.3': ('3.3', 18, 18, False), '1': ('1', 18, 18, False),
    '12': ('12', 18, 18, False), '9.4': ('9.4', 18, 18, False), '7.9': ('7.9', 18, 18, False), '4.7': ('4.7', 18, 18, False),
    '5.9': ('5.9', 18, 18, False), '3.9': ('3.9', 18, 18, False), '2.4': ('2.4', 18, 18, False),
}


def render(font_path, text, figure, baseline, centred, tracking=0.6):
    probe = ImageFont.truetype(font_path, size=200)
    b = probe.getbbox('0', anchor='ls')
    size = 200 * figure * SS / (b[3] - b[1])
    font = ImageFont.truetype(font_path, size=size)
    under = font.getbbox('0', anchor='ls')[3]   # the overshoot of the round figures below the baseline
    big = Image.new('L', (W * SS * 2, H * SS), 0)
    draw = ImageDraw.Draw(big)
    x = 0.0
    for ch in text:
        draw.text((x, (baseline + 1) * SS - under), ch, fill=255, font=font, anchor='ls')
        x += font.getlength(ch) + tracking * SS
    box = big.getbbox()
    if box is None: sys.exit(f'{text}: nothing drawn')
    big = big.crop((box[0], 0, box[2], H * SS))
    ink = big.width / SS
    if ink > W - 2:   # narrower, as the camera's own three-character labels are: never more than the icon's width less the outline
        big = big.resize((int((W - 2) * SS), H * SS), Image.LANCZOS)
        ink = W - 2
    left = int(round((W - ink) / 2)) if centred else 1
    pad = Image.new('L', (W * SS, H * SS), 0)
    pad.paste(big, (left * SS, 0))
    cov = np.asarray(pad.resize((W, H), Image.BOX), dtype=np.float64) / 255
    canvas = cov
    ink = canvas > 0.02
    edge = np.zeros_like(ink)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            s = np.zeros_like(ink)
            s[max(dy, 0):H + min(dy, 0), max(dx, 0):W + min(dx, 0)] = ink[max(-dy, 0):H - max(dy, 0), max(-dx, 0):W - max(dx, 0)]
            edge |= s
    if ink[0].any() or ink[-1].any() or ink[:, 0].any() or ink[:, -1].any(): sys.exit(f'{text}: no room for the outline')
    grey = np.clip(np.round(canvas * 255), 0, 254).astype(np.uint8)
    return np.where(edge, grey.astype(np.int32) + 1, 0).astype(np.uint8)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('font')
    ap.add_argument('--sheet')
    a = ap.parse_args()
    icons = {name: render(a.font, *spec) for name, spec in LABELS.items()}
    rows = [f"  '{name}': '{base64.b64encode(px.tobytes()).decode()}'," for name, px in icons.items()]
    OUT.write_text('// SPDX-License-Identifier: GPL-2.0-only\n'
                   '// GENERATED by tools/units/labels.py -- do not edit.\n'
                   '/** The feet / inch labels of the manual focus scale, 30 x 20: per pixel 0 transparent, else 1 + grey (opaque). */\n'
                   'export const UNIT_LABELS: Readonly<Record<string, string>> = {\n' + '\n'.join(rows) + '\n};\n')
    print('wrote', OUT.relative_to(REPO))
    if a.sheet:
        sc = 6
        sheet = Image.new('RGB', (len(icons) * (W * sc + 8), H * sc + 8), (40, 40, 40))
        for k, px in enumerate(icons.values()):
            v = px.astype(np.int32)
            rgba = np.zeros((H, W, 4), np.uint8)
            g = np.clip(v - 1, 0, 255).astype(np.uint8)
            rgba[..., 0] = rgba[..., 1] = rgba[..., 2] = g
            rgba[..., 3] = np.where(v > 0, 255, 0)
            im = Image.fromarray(rgba, 'RGBA').resize((W * sc, H * sc), Image.NEAREST)
            sheet.paste(im, (4 + k * (W * sc + 8), 4), im)
        sheet.save(a.sheet)


if __name__ == '__main__':
    main()
