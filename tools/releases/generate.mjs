/**
 * The official firmware releases GR Mod builds on are listed once, in releases.json at the root.
 * This writes that list into the programs that need it:
 *
 *   shell/internal/ricoh/releases_gen.go                         the desktop shell's downloads
 *   mobile/android/.../push/Ricoh.java      (between the markers)  the Android app's
 *   mobile/ios-plugin/.../GrCamera/Ricoh.swift (between the markers)  the iOS app's
 *   ui/src/releases.gen.ts                                       what the UI offers and names
 *   README.md                               (between the markers)  the table of supported firmware
 *
 *   node tools/releases/generate.mjs           write them
 *   node tools/releases/generate.mjs --check   fail when one of them is not what would be written
 *
 * Both also compare the list with the engine: every `firmwareSha256` must be an official file one
 * of the programs in core/src/fw opens, and every file they open must be listed.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const check = process.argv.includes('--check');
const list = JSON.parse(readFileSync(join(ROOT, 'releases.json'), 'utf8'));
const groups = list.groups;
const problems = [];

// ---------------------------------------------------------------- the list itself
const HEX = /^[0-9a-f]{64}$/;
for (const g of groups) {
  if (!g.id || !g.name || !g.applies || !g.page || !g.models?.length || !g.releases?.length) problems.push(`releases.json: group ${g.id ?? '?'} is incomplete`);
  const versions = g.releases.map((r) => r.version);
  const sorted = [...versions].sort((a, b) => cmp(b, a));
  if (versions.join() !== sorted.join()) problems.push(`releases.json: ${g.id} is not newest first`);
  for (const r of g.releases) {
    if (!/^\d{1,2}\.\d{1,3}$/.test(r.version)) problems.push(`releases.json: ${g.id} ${r.version}: version`);
    if (!/^[a-z0-9_]+\.zip$/.test(r.file)) problems.push(`releases.json: ${g.id} ${r.version}: file`);
    if (r.date && !/^\d{4}\/\d{2}\/\d{2}$/.test(r.date)) problems.push(`releases.json: ${g.id} ${r.version}: date`);
    if (r.sha256 === null ? r.size !== 0 : !(HEX.test(r.sha256) && Number.isSafeInteger(r.size) && r.size > 0)) problems.push(`releases.json: ${g.id} ${r.version}: size / sha256`);
    if (!HEX.test(r.firmwareSha256)) problems.push(`releases.json: ${g.id} ${r.version}: firmwareSha256`);
  }
}
function cmp(a, b) {
  const x = a.split('.').map(Number), y = b.split('.').map(Number);
  for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) - (y[i] ?? 0);
  return 0;
}

// ---------------------------------------------------------------- against the engine
// The official files the engine opens: `OFFICIAL_SHA256 = '...'` (GR IV programs) and the `sha256:`
// of the GR III / IIIx profiles (fw/gr3-profiles.ts).
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out); else if (name === 'profile.ts' || name === 'gr3-profiles.ts') out.push(p);
  }
  return out;
}
const engine = new Set();
for (const f of walk(join(ROOT, 'core/src/fw'))) {
  const t = readFileSync(f, 'utf8');
  // one hash, or byRelease({ '1.20': '...', '1.21': '...' }) for a program of several releases
  for (const m of t.matchAll(/OFFICIAL_SHA256\s*=\s*(?:'[0-9a-f]{64}'|byRelease\(\{[^}]*\}\))/g)) for (const h of m[0].matchAll(/'([0-9a-f]{64})'/g)) engine.add(h[1]);
  for (const m of t.matchAll(/^\s*sha256:\s*'([0-9a-f]{64})'/gm)) engine.add(m[1]);
}
const listed = new Set(groups.flatMap((g) => g.releases.map((r) => r.firmwareSha256)));
for (const g of groups) for (const r of g.releases) if (!engine.has(r.firmwareSha256)) problems.push(`releases.json: ${g.name} ${r.version}: no program in core/src/fw opens the file ${r.firmwareSha256.slice(0, 8)}…`);
for (const s of engine) if (!listed.has(s)) problems.push(`core/src/fw opens the official file ${s.slice(0, 8)}…, which releases.json does not list`);

// ---------------------------------------------------------------- outputs
const outputs = [];
const NOTE = 'GENERATED by tools/releases/generate.mjs from releases.json. Do not edit.';
const q = (s) => JSON.stringify(s);

/** Replaces what is between the BEGIN and END marker lines of a file (the markers stay). */
function between(path, begin, end, body) {
  const t = readFileSync(join(ROOT, path), 'utf8');
  const a = t.indexOf(begin), b = t.indexOf(end);
  if (a < 0 || b < a) { problems.push(`${path}: the markers "${begin}" / "${end}" are missing`); return; }
  const lineEnd = t.indexOf('\n', a) + 1, lineStart = t.lastIndexOf('\n', b) + 1;
  outputs.push([path, t.slice(0, lineEnd) + body + t.slice(lineStart)]);
}

// --- Go: the shell keeps the newest and the oldest GR IV release apart (Supported, Earlier), fetches
// the archives that have no checksum by name (pinned) and offers the rest as Others.
{
  const gr4 = groups.find((g) => g.id === 'gr4');
  const arch = (g, r, pad) => [
    `${pad}Version: ${q(r.version)},`, ...(r.date ? [`${pad}Date:    ${q(r.date)},`] : []),
    `${pad}Path:    ${q(list.archives + r.file)},`, `${pad}Size:    ${r.size},`, `${pad}SHA256:  ${q(r.sha256)},`,
    `${pad}Models:  []string{${g.models.map(q).join(', ')}},`, `${pad}Applies: ${q(g.applies)},`, `${pad}Page:    ${q(g.page)},`,
  ].join('\n');
  const newest = gr4.releases[0], oldest = gr4.releases[gr4.releases.length - 1];
  const others = [], pinned = [];
  for (const g of groups) for (const r of g.releases) {
    if (r.sha256 === null) { for (const m of g.models) pinned.push([m, g, r]); continue; }
    if (g === gr4 && (r === newest || r === oldest)) continue;
    others.push([g, r]);
  }
  const go = `// Code ${NOTE}

package ricoh

// pinned are the releases whose archives have no known checksum (the earliest GR III / IIIx
// releases GR Mod builds on). The site's pages list only the current release, so these are fetched
// by name; the engine checks the SHA-256 of the file inside.
var pinned = map[string]Release{
${pinned.map(([m, g, r]) => `\t${q(m)}: {Name: ${q(g.name)}, Applies: ${q(g.applies)},\n\t\tVersion: ${q(r.version)}, Date: ${q(r.date)}, File: ${q(r.file)},\n\t\tPage: ${q(g.page)}, URL: ${q(list.archives + r.file)}},`).join('\n')}
}

// Supported is the newest GR IV / GR IV HDF release this program builds on.
var Supported = Archive{
${arch(gr4, newest, '\t')}
}

// Earlier is the oldest GR IV release this program builds on, which Ricoh still serves at a
// fixed address; it is offered next to Supported and the releases in Others.
var Earlier = Archive{
${arch(gr4, oldest, '\t')}
}

// Others are the remaining releases this program builds on, still served at fixed addresses
// once the site's pages list a newer one.
var Others = []Archive{
${others.map(([g, r]) => `\t{\n${arch(g, r, '\t\t')}\n\t},`).join('\n')}
}
`;
  outputs.push(['shell/internal/ricoh/releases_gen.go', go]);
}

// --- Java and Swift: per model, newest first.
{
  const java = [], swift = [], map = [];
  for (const g of groups) {
    java.push(`        List<Release> ${g.id} = new ArrayList<>();`);
    swift.push(`        let ${g.id} = [`);
    for (const r of g.releases) {
      java.push(`        ${g.id}.add(pin(${q(g.name)}, ${q(g.applies)}, ${q(r.version)}, ${q(r.date)}, ${q(r.file)}, ${r.size}L,\n                ${r.sha256 === null ? 'null' : q(r.sha256)}, ${q(g.page)}));`);
      swift.push(`            pin(${q(g.name)}, ${q(g.applies)}, ${q(r.version)}, ${q(r.date)}, ${q(r.file)}, ${r.size}, ${r.sha256 === null ? 'nil' : q(r.sha256)}, ${q(g.page)}),`);
    }
    swift.push('        ]');
    for (const m of g.models) { java.push(`        SUPPORTED.put(${q(m)}, ${g.id});`); map.push(`${q(m)}: ${g.id}`); }
  }
  swift.push(`        return [${map.join(', ')}]`);
  between('mobile/android/app/src/main/java/io/github/maxwooow/grmod/push/Ricoh.java', '// BEGIN releases', '// END releases', java.join('\n') + '\n');
  between('mobile/ios-plugin/ios/Sources/GrCamera/Ricoh.swift', '// BEGIN releases', '// END releases', swift.join('\n') + '\n');
}

// --- UI: what each model can be built on, and the list an unusable file is answered with.
{
  const models = groups.flatMap((g) => g.models.map((m) => `  ${m}: [${g.releases.map((r) => q(r.version)).join(', ')}],`));
  const ts = `// ${NOTE}

/** The official releases GR Mod builds on, per model, newest first. */
export const SUPPORTED_RELEASES = {
${models.join('\n')}
} as const;

/** The same for a message: one entry per camera line. */
export const SUPPORTED_LINES: readonly { name: string; versions: readonly string[] }[] = [
${groups.map((g) => `  { name: ${q(g.name)}, versions: [${g.releases.map((r) => q(r.version)).join(', ')}] },`).join('\n')}
];
`;
  outputs.push(['ui/src/releases.gen.ts', ts]);
}

// --- README: the table of supported firmware.
{
  const or = (v) => (v.length > 1 ? `${v.slice(0, -1).join(', ')} or ${v[v.length - 1]}` : v[0]);
  const rows = groups.map((g) => `| ${g.label} | ${or(g.releases.map((r) => r.version))}${g.note ? ` (${g.note})` : ''} |`);
  between('README.md', '<!-- BEGIN releases', '<!-- END releases', `\n| Camera | Supported firmware |\n| --- | --- |\n${rows.join('\n')}\n\n`);
}

// ---------------------------------------------------------------- write or compare
for (const [path, text] of outputs) {
  let now = null;
  try { now = readFileSync(join(ROOT, path), 'utf8'); } catch { /* new file */ }
  if (now === text) continue;
  if (check) problems.push(`${path}: not what releases.json gives (run node tools/releases/generate.mjs)`);
  else { writeFileSync(join(ROOT, path), text); console.log('wrote', path); }
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
console.log(check ? 'releases: every list is up to date' : 'releases: done');
