"""Generate the imprint's printable ASCII cells with the bundled OFL Courier Prime Bold.

Run with Pillow installed. Each character is a 16x24 grayscale coverage cell;
all glyphs share the baseline, preserving lowercase and punctuation.
"""
import base64
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
FONT = HERE / 'fonts/CourierPrime-Bold.ttf'


def build():
    scale = 4
    font = ImageFont.truetype(str(FONT), 30 * scale)
    data = bytearray()
    for code in range(32, 127):
        image = Image.new('L', (24 * scale, 28 * scale))
        ImageDraw.Draw(image).text((12 * scale, 21 * scale), chr(code), font=font, fill=255, anchor='ms')
        data.extend(image.resize((16, 24), Image.Resampling.LANCZOS).tobytes())
    assert len(data) == 95 * 16 * 24
    return bytes(data)


if __name__ == '__main__':
    path = HERE.parents[1] / 'core/src/fw/aspect/datestamp-font.ts'
    encoded = base64.b64encode(build()).decode()
    path.write_text('// SPDX-License-Identifier: GPL-2.0-only\n'
                    '// Generated by tools/datestamp/font.py. ASCII 16x24 coverage cells.\n'
                    '// Typeface: Courier Prime Bold; SIL Open Font License, tools/datestamp/fonts/OFL.txt.\n'
                    'export const DATESTAMP_FONT_BASE64 = ' + repr(encoded) + ';\n')
    print(path)
