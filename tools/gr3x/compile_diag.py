"""Compile GR III's builds of the picture modules (date imprint, halation).

 - tools/datestamp/datestamp.c with -DSTRICT_PLANES -DSETTING_RECORD: the date imprint of GR III
   builds. Its setting byte lies in the user-settings record, reached through the record pointer
   (0 before the settings are loaded); it writes only planes above 0x5d000000.

 - tools/datestamp/datestamp.c with -DDIAG -DSTRICT_PLANES -DGR3_WORDS: like GR IV's diagnostic
   build, but it only writes into picture planes above 0x5d000000 (above GR III's RTOS data and
   heaps) whose CbCr plane has the rows it draws; the configuration and the picture descriptors are
   read wherever they are. Row 0 also shows two words: the halation stash and the halation status.
 - tools/halation/halation.c with -DSTATUS: GR IV's halation, which also leaves a status word
   (how far it got, the first picture's format and why it was refused) for the line above.

Both position independent (checked by linking at two addresses, as gen.py). Writes
core/src/fw/gr3x/picture-modules.ts. Round 7 (GR Mod 0.8.2 sources): the date imprint's context ends with
GR IV's look fields (the stash word, the 64-byte table of black-and-white looks, the model check)
and the halation is 0.8.2's ('HAL4': three levels, red / white). Round 6's builds of the older
sources are kept in picture-modules-r6.ts, round 7's date imprint in picture-modules-r7.ts. Round 8
(GR Mod 0.8.4 sources) adds -DGR3_PACKED: the orientation and the look of the picture being made
are a byte and a halfword (see jpeg-stage.ts) instead of GR IV's two words. GR IV's datestamp-code.ts and halation-code.ts are not
regenerated; their builds do not define these macros, and GR IV's builds of the edited sources
equal those of the sources before the edit (same compiler).
"""
import base64,hashlib,importlib.util,sys,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def load(name):
    spec=importlib.util.spec_from_file_location(f'gen_{name}',ROOT/'tools'/name/'gen.py')
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m
def pic(gen,flags):
    cc,ld,objcopy=gen.tools()
    with tempfile.TemporaryDirectory() as t:
        tmp=Path(t)
        a=gen.build(cc,ld,objcopy,tmp,0x10000,flags)
        b=gen.build(cc,ld,objcopy,tmp,0x543f0000,flags)
    if a!=b:sys.exit(f'{gen.SRC.name} is not position independent')
    while len(a)%4:a+=b'\0'
    return a,gen.run(cc+['--version']).splitlines()[0]
def main():
    ds,ha=load('datestamp'),load('halation')
    release,version=pic(ds,['-DSTRICT_PLANES','-DSETTING_RECORD','-DGR3_PACKED'])
    date,_=pic(ds,['-DDIAG','-DSTRICT_PLANES','-DGR3_WORDS'])
    halo,_=pic(ha,['-DSTATUS'])
    out=ROOT/'core'/'src'/'fw'/'gr3x'/'picture-modules.ts'
    out.write_text('// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr3x/compile_diag.py from tools/datestamp/datestamp.c (-DSTRICT_PLANES -DSETTING_RECORD -DGR3_PACKED;\n'
        '// -DDIAG -DSTRICT_PLANES -DGR3_WORDS) and tools/halation/halation.c (-DSTATUS).\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256: {hashlib.sha256(ds.SRC.read_bytes()).hexdigest()} (datestamp.c), {hashlib.sha256(ha.SRC.read_bytes()).hexdigest()} (halation.c)\n'
        "/** GR III round 8 (GR Mod 0.8.4 sources): the date imprint (context: cache, invalidate, clean,\n"
        " * platform, get time, address of the settings-record pointer, offset of the setting byte, the look\n"
        " * stash, the table of black-and-white looks, the model check, the orientation byte, the frame-look\n"
        " * halfword, the look-name table). Writes planes above 0x5d000000 only. */\n"
        f"export const GR3X_DATESTAMP_CODE = '{base64.b64encode(release).decode()}';\n"
        "/** GR III test builds: the date imprint's diagnostic module (writes planes above 0x5d000000 only;\n"
        " * its context has a seventh word, the address of the halation stash and status words, then the\n"
        " * three look words). */\n"
        f"export const GR3X_DATESTAMP_DIAG_CODE = '{base64.b64encode(date).decode()}';\n"
        "/** GR III test builds: halation ('HAL4') with a status word (its context has the word's address\n"
        " * after the look map). */\n"
        f"export const GR3X_HALATION_STATUS_CODE = '{base64.b64encode(halo).decode()}';\n")
    # Round 10: GR IV's words for the orientation and the frame look (no -DGR3_PACKED).
    r10,_=pic(ds,['-DSTRICT_PLANES','-DSETTING_RECORD'])
    (ROOT/'core'/'src'/'fw'/'gr3x'/'picture-modules-r10.ts').write_text('// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr3x/compile_diag.py from tools/datestamp/datestamp.c (-DSTRICT_PLANES -DSETTING_RECORD).\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256: {hashlib.sha256(ds.SRC.read_bytes()).hexdigest()} (datestamp.c)\n'
        "/** GR III round 10: the date imprint with GR IV's words (context as round 8's, but the orientation\n"
        " * word, value | 0x100, and the frame-look word, the look stash's word, as GR IV's ORIENT_WORD and\n"
        " * FRAME_LOOK). Writes planes above 0x5d000000 only. */\n"
        f"export const GR3X_DATESTAMP_R10_CODE = '{base64.b64encode(r10).decode()}';\n")
    print(len(release),len(date),len(halo),len(r10))
main()
