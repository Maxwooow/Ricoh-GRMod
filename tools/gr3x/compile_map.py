"""Compile the IIIx C module to an A32 relocatable template using local clang.

Only explicit ELF32 ARM .text, named symbols and four audited relocation kinds
are accepted. No host executable is run; unexpected sections or references fail.
"""
import hashlib
import json
import struct
import subprocess
import tempfile
from pathlib import Path

REPO=Path(__file__).resolve().parents[2]
source=Path(__file__).with_name('native')/'map.c'
flags=['-target','armv7-none-eabi','-mcpu=cortex-a9','-marm','-mfloat-abi=soft','-Os',
       '-ffreestanding','-fno-builtin','-fno-unwind-tables','-fno-asynchronous-unwind-tables','-c']
with tempfile.TemporaryDirectory(prefix='gr3x-map-') as folder:
    obj=Path(folder)/'map.o'
    subprocess.run(['/usr/bin/clang',*flags,str(source),'-o',str(obj)],check=True)
    b=obj.read_bytes()
assert b[:7]==b'\x7fELF\x01\x01\x01' and struct.unpack_from('<HH',b,16)==(1,40)
shoff=struct.unpack_from('<I',b,32)[0]
shsize,count,names=struct.unpack_from('<HHH',b,46)
sections=[struct.unpack_from('<10I',b,shoff+i*shsize) for i in range(count)]
def section_bytes(i):
    s=sections[i];return b[s[4]:s[4]+s[5]]
def zstr(buf,off):return buf[off:].split(b'\0',1)[0].decode()
names_blob=section_bytes(names)
section_names=[zstr(names_blob,s[0]) for s in sections]
ti=section_names.index('.text');text=section_bytes(ti)
for name,s in zip(section_names,sections):
    if s[2]&2 and s[5] and name not in ('.text','.ARM.exidx'):
        raise ValueError('Unexpected allocated section: '+name)
si=next(i for i,s in enumerate(sections) if s[1]==2)
strings=section_bytes(sections[si][6]);sb=section_bytes(si)
symbols=[]
for at in range(0,len(sb),16):
    name,value,size,info,other,index=struct.unpack_from('<IIIBBH',sb,at)
    symbols.append(dict(name=zstr(strings,name),value=value,size=size,info=info,index=index))
exports={s['name']:s['value'] for s in symbols if s['index']==ti and s['info']>>4==1}
assert set(exports)=={'crop_identity','crop_make_view','crop_clone_tail'}
relocs=[]
for i,s in enumerate(sections):
    if s[1]!=9 or s[7]!=ti:continue
    data=section_bytes(i)
    for at in range(0,len(data),8):
        off,info=struct.unpack_from('<II',data,at);kind=info&255;sym=symbols[info>>8]
        assert kind in (28,29,43,44),(kind,sym)
        assert sym['index']==ti or (sym['index']==0 and sym['name']=='ratios'),sym
        word=struct.unpack_from('<I',text,off)[0]
        if kind in (28,29):
            val=word&0xffffff
            if val&0x800000:val-=1<<24
            addend=4*val+8
        else:addend=((word>>4)&0xf000)|(word&0xfff)
        # This module has no address+constant MOVW/MOVT relocations.
        if kind in (43,44):assert addend==0
        relocs.append([off,kind,'ratios' if sym['index']==0 else sym['value'],addend])
result=dict(sourceSha256=hashlib.sha256(source.read_bytes()).hexdigest(),code=text.hex(),exports=exports,relocs=relocs)
out=REPO/'core/src/fw/gr3x/map-native.ts'
out.write_text('// SPDX-License-Identifier: GPL-2.0-only\n// Generated by tools/gr3x/compile_map.py from native/map.c.\nexport const GR3X_MAP_NATIVE = '+json.dumps(result,indent=2)+' as const;\n')
print(json.dumps(dict(bytes=len(text),relocations=len(relocs),exports=exports,source_sha256=result['sourceSha256'])))
