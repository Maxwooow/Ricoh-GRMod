"""Compile vafquick.c for the camera (ARMv7-A, ARM mode, soft float) and write core/src/fw/gr4v120/aspect/videoaf-code.ts.
1.21 shares the 1.20 port's module (core/overlays.mjs): it names no firmware address (the context passes them in), so this
compiles tools/gr4v120/videoaf/vafquick.c, the same as the 1.20 copy does.
Checks: identical when linked at two addresses (position independent), no .data / .bss / .rodata / .got, no undefined symbol
(no library calls), entry `vafquick` at offset 0.  Needs `python -m ziglang`; the ELF is read here."""
import base64, hashlib, os, struct, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / 'core' / 'src' / 'fw' / 'gr4v120' / 'aspect'
SRC = ROOT / 'tools' / 'gr4v120' / 'videoaf' / 'vafquick.c'   # the shared module's source
Z = [sys.executable, '-m', 'ziglang']
FLAGS = ['-target', 'arm-freestanding-eabi', '-mcpu=cortex_a7', '-marm', '-mfloat-abi=soft', '-O2', '-fomit-frame-pointer', '-ffreestanding', '-fno-builtin',
         '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-nostdlib', '-fropi', '-frwpi', '-fno-jump-tables', '-Wall', '-Wextra', '-Werror']


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if r.returncode: sys.exit(' '.join(map(str, cmd)) + '\n' + r.stdout + r.stderr)
    return r.stdout


def elf32(d):
    """Section sizes by name, and symbols as name -> (value, defined), of a little-endian ELF32 file."""
    assert d[:6] == b'\x7fELF\x01\x01'
    shoff, = struct.unpack_from('<I', d, 0x20); shentsize, shnum, shstrndx = struct.unpack_from('<3H', d, 0x2e)
    sh = [struct.unpack_from('<10I', d, shoff + i * shentsize) for i in range(shnum)]
    text = lambda tab, off: d[tab + off:d.index(b'\0', tab + off)].decode()
    sections = {text(sh[shstrndx][4], s[0]): s[5] for s in sh}
    symbols = {}
    for s in sh:
        if s[1] == 2:                                                    # SHT_SYMTAB
            for o in range(s[4], s[4] + s[5], 16):
                name, value, _, info, _, shndx = struct.unpack_from('<IIIBBH', d, o)
                if info & 15 in (0, 1, 2) and name: symbols[text(sh[s[6]][4], name)] = (value, shndx != 0)
    return sections, symbols


def build():
    os.environ.setdefault('ZIG_GLOBAL_CACHE_DIR', os.path.join(tempfile.gettempdir(), 'zigg')); os.environ.setdefault('ZIG_LOCAL_CACHE_DIR', os.path.join(tempfile.gettempdir(), 'zigl'))
    with tempfile.TemporaryDirectory() as t:
        t = Path(t); obj = t / 'vafquick.o'
        run(Z + ['cc'] + FLAGS + ['-c', SRC, '-o', obj])
        outs = []
        for origin in (0x10000, 0x54430000):
            elf = t / f'a{origin:x}.elf'
            run(Z + ['ld.lld', f'-Ttext=0x{origin:x}', '--entry=vafquick', '-o', elf, obj])
            run(Z + ['objcopy', '-O', 'binary', '-j', '.text', elf, t / 'a.bin'])
            outs.append((t / 'a.bin').read_bytes())
            sections, symbols = elf32(elf.read_bytes())
            for name, size in sections.items():
                if size and name.split('.')[1:2] and name.split('.')[1] in ('data', 'bss', 'rodata', 'got'): sys.exit(f'module has a {name} section')
            if symbols.get('vafquick') != (origin, True): sys.exit('vafquick is not at the start of .text')
            if any(not defined for n, (_, defined) in symbols.items() if n): sys.exit('undefined symbols')
        if outs[0] != outs[1]: sys.exit('not position independent')
        return outs[0] + b'\0' * (-len(outs[0]) % 4)


def main():
    code = build()
    src = hashlib.sha256(SRC.read_bytes()).hexdigest()
    (OUT / 'videoaf-code.ts').write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr4v120/videoaf/gen.py from vafquick.c -- do not edit.\n'
        f'// Source SHA-256: {src}\n'
        '// Position independent; entry `vafquick(ctx, which, a, b)` at offset 0; ctx: struct ctx in vafquick.c.\n\n'
        f"export const VAFQUICK_CODE = '{base64.b64encode(code).decode()}';\n"
        f'export const VAFQUICK_CODE_LENGTH = {len(code)};\n'
)
    print(f'module {len(code)} bytes')


if __name__ == '__main__':
    main()
