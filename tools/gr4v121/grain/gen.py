"""Compile tools/gr4v121/grain/grain.c and write core/src/fw/gr4v120/aspect/grain-code.ts, which 1.21 shares.

The module is position independent (-fropi -frwpi, no global data, every address passed in through
its context argument), so the bytes do not depend on where they are placed. This is checked by
linking it at two addresses and comparing. Compiler: clang if present, else `python3 -m ziglang cc`
(pip install ziglang; set GRMOD_ZIG=1 to use it even when clang is installed); flags as for the ratio modules (cortex-a9, ARM, soft float, -Os, no library).
"""
import base64
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
SRC = HERE / 'grain.c'
OUT = ROOT / 'core' / 'src' / 'fw' / 'gr4v120' / 'aspect' / 'grain-code.ts'   # shared by 1.21 (core/overlays.mjs)
USE_ZIG = bool(os.environ.get('GRMOD_ZIG')) or not (shutil.which('clang') and shutil.which('ld.lld') and shutil.which('llvm-objcopy'))
FLAGS = ['-mcpu=cortex_a9' if USE_ZIG else '-mcpu=cortex-a9', '-marm', '-mfloat-abi=soft', '-O2',
         '-ffreestanding', '-fno-builtin', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-nostdlib',
         '-fropi', '-frwpi', '-fno-jump-tables', '-Wall', '-Wextra', '-Werror']


def tools():
    if not USE_ZIG:
        return ['clang', '-target', 'armv7-none-eabi'], ['ld.lld'], ['llvm-objcopy']
    z = [sys.executable, '-m', 'ziglang']
    return z + ['cc', '-target', 'arm-freestanding-eabi'], z + ['ld.lld'], z + ['objcopy']


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'{" ".join(map(str, cmd))}\n{r.stdout}{r.stderr}')
    return r.stdout


def elf_info(path):
    """Section names and the address of `film_grain` of a 32-bit little-endian ELF (no readelf needed)."""
    import struct
    b = Path(path).read_bytes()
    shoff, = struct.unpack_from('<I', b, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from('<HHH', b, 0x2e)
    sh = [struct.unpack_from('<IIIIIIIIII', b, shoff + i * shentsize) for i in range(shnum)]
    strtab = sh[shstrndx]
    def name(off, tab):
        e = b.index(0, tab[4] + off)
        return b[tab[4] + off:e].decode()
    names = [name(x[0], strtab) for x in sh]
    entry = None
    for x in sh:
        if x[1] == 2:  # SHT_SYMTAB
            link = sh[x[6]]
            for i in range(x[5] // 16):
                st_name, st_value = struct.unpack_from('<II', b, x[4] + i * 16)
                if name(st_name, link) == 'film_grain':
                    entry = st_value
    return names, entry


def build(cc, ld, objcopy, tmp, origin, extra=()):
    obj = tmp / 'gr.o'
    run(cc + FLAGS + list(extra) + ['-c', SRC, '-o', obj])
    elf = tmp / f'gr_{origin:x}.elf'
    run(ld + [f'-Ttext=0x{origin:x}', '--entry=film_grain', '-o', elf, obj])
    out = tmp / f'gr_{origin:x}.bin'
    run(objcopy + ['-O', 'binary', '-j', '.text', elf, out])
    names, entry = elf_info(elf)
    for name in ('.data', '.bss', '.rodata', '.got'):
        if any(n == name or n.startswith(name + '.') for n in names):
            sys.exit(f'module has a {name} section')
    if entry != origin:
        sys.exit('film_grain is not at the start of .text')
    return out.read_bytes()


def main():
    cc, ld, objcopy = tools()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        a = build(cc, ld, objcopy, tmp, 0x10000)
        b = build(cc, ld, objcopy, tmp, 0x54430000)
    if a != b:
        sys.exit('module is not position independent')
    while len(a) % 4:
        a += b'\0'
    version = run(cc + ['--version']).splitlines()[0]
    src_hash = hashlib.sha256(SRC.read_bytes()).hexdigest()
    OUT.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr4v121/grain/gen.py from tools/gr4v121/grain/grain.c -- do not edit.\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256: {src_hash}\n'
        '// Position independent: entry `film_grain(ctx, config)` at offset 0.\n\n'
        f"export const GRAIN_CODE = '{base64.b64encode(a).decode()}';\n"
        f'export const GRAIN_CODE_LENGTH = {len(a)};\n'
        f"export const GRAIN_SOURCE_SHA256 = '{src_hash}';\n")
    print(f'{OUT}: {len(a)} bytes')


if __name__ == '__main__':
    main()
