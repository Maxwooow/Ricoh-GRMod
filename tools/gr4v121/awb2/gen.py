"""Compile awb2.c for the camera (ARMv7-A, ARM mode, soft float) and write core/src/fw/gr4v120/aspect/awb2-code.ts (the module and
the table blob; GR IV 1.20 and 1.21 use the same bytes). Checks: identical when linked at two addresses (position independent), no .data / .bss / .rodata / .got,
no undefined symbol (no library calls), entry `awb2` at offset 0.  Needs `python -m ziglang`; the ELF is read here."""
import base64, hashlib, os, struct, subprocess, sys, tempfile
from pathlib import Path
import tables

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
# 1.21 uses the 1.20 port's module and tables (core/overlays.mjs): they name no firmware address (the context passes them in),
# and awb2.c here is the same file as tools/gr4v120/awb2/awb2.c, so this writes the same bytes as the 1.20 copy.
OUT = ROOT / 'core' / 'src' / 'fw' / 'gr4v120' / 'aspect'
Z = [sys.executable, '-m', 'ziglang']
FLAGS = ['-target', 'arm-freestanding-eabi', '-mcpu=cortex_a7', '-marm', '-mfloat-abi=soft', '-O2', '-fomit-frame-pointer', '-ffreestanding', '-fno-builtin',
         '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-nostdlib', '-fropi', '-frwpi', '-fno-jump-tables', '-Wall', '-Wextra', '-Werror']
ORDER = ['lnm', 'ff', 'bias', 'tw', 'tanh', 'exp2n', 'atan', 'cs20', 'rc']          # the table pointers of struct awb2_ctx after magic, alloc, slot


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if r.returncode: sys.exit(' '.join(map(str, cmd)) + '\n' + r.stdout + r.stderr)
    return r.stdout


def elf32(d):
    """Section sizes by name, and symbols as name -> (value, defined), of a little-endian ELF32 file."""
    assert d[:6] == b'\x7fELF\x01\x01'
    shoff, = struct.unpack_from('<I', d, 0x20); shentsize, shnum, shstrndx = struct.unpack_from('<3H', d, 0x2e)
    sh = [struct.unpack_from('<10I', d, shoff + i * shentsize) for i in range(shnum)]
    text = lambda tab, off: d[tab + off:d.index(b'\0', tab + off)].decode()
    sections = {text(sh[shstrndx][4], s[0]): s[5] for s in sh}
    symbols = {}
    for s in sh:
        if s[1] == 2:                                                    # SHT_SYMTAB
            for o in range(s[4], s[4] + s[5], 16):
                name, value, _, info, _, shndx = struct.unpack_from('<IIIBBH', d, o)
                if info & 15 in (0, 1, 2) and name: symbols[text(sh[s[6]][4], name)] = (value, shndx != 0)
    return sections, symbols


def build():
    T, C = tables.build()
    (HERE / 'awb2_const.h').write_text(tables.header(C))
    os.environ.setdefault('ZIG_GLOBAL_CACHE_DIR', os.path.join(tempfile.gettempdir(), 'zigg')); os.environ.setdefault('ZIG_LOCAL_CACHE_DIR', os.path.join(tempfile.gettempdir(), 'zigl'))
    with tempfile.TemporaryDirectory() as t:
        t = Path(t); obj = t / 'awb2.o'
        run(Z + ['cc'] + FLAGS + ['-I', HERE, '-c', HERE / 'awb2.c', '-o', obj])
        outs = []
        for origin in (0x10000, 0x54430000):
            elf = t / f'a{origin:x}.elf'
            run(Z + ['ld.lld', f'-Ttext=0x{origin:x}', '--entry=awb2', '-o', elf, obj])
            run(Z + ['objcopy', '-O', 'binary', '-j', '.text', elf, t / 'a.bin'])
            outs.append((t / 'a.bin').read_bytes())
            sections, symbols = elf32(elf.read_bytes())
            for name, size in sections.items():
                if size and name.split('.')[1:2] and name.split('.')[1] in ('data', 'bss', 'rodata', 'got'): sys.exit(f'module has a {name} section')
            if symbols.get('awb2') != (origin, True): sys.exit('awb2 is not at the start of .text')
            if any(not defined for n, (_, defined) in symbols.items() if n): sys.exit('undefined symbols')
        if outs[0] != outs[1]: sys.exit('not position independent')
        code = outs[0] + b'\0' * (-len(outs[0]) % 4)
    blob = bytearray(); offs = {}
    for name in ORDER:
        blob += b'\0' * (-len(blob) % 4)
        offs[name] = len(blob); blob += T[name].astype(T[name].dtype.newbyteorder('<')).tobytes()
    blob += b'\0' * (-len(blob) % 4)
    return code, bytes(blob), offs, C


def main():
    code, blob, offs, C = build()
    src = hashlib.sha256((HERE / 'awb2.c').read_bytes() + (HERE / 'awb2_const.h').read_bytes()).hexdigest()
    (OUT / 'awb2-code.ts').write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr4v120/awb2/gen.py from awb2.c (+ awb2_const.h) and tables.py (trained parameters model/illum_v2.npz) -- do not edit.\n'
        f'// Source SHA-256 (awb2.c followed by awb2_const.h): {src}\n'
        '// Module: position independent, entry `awb2(ctx, obj, S, rec)` at offset 0, ctx layout: struct awb2_ctx in awb2.c.\n'
        '// Tables: little endian, every table 4-byte aligned; AWB2_OFFSETS in the order of the table pointers of struct awb2_ctx.\n\n'
        f"export const AWB2_CODE = '{base64.b64encode(code).decode()}';\n"
        f'export const AWB2_CODE_LENGTH = {len(code)};\n'
        f'export const AWB2_MAGIC = 0x{C["MAGIC"]:08x};\n'
        f"export const AWB2_DATA = '{base64.b64encode(blob).decode()}';\n"
        f'export const AWB2_DATA_LENGTH = {len(blob)};\n'
        f"export const AWB2_DATA_SHA256 = '{hashlib.sha256(blob).hexdigest()}';\n"
        'export const AWB2_OFFSETS = [' + ', '.join(str(offs[n]) for n in ORDER) + '] as const;\n')
    print(f'module {len(code)} bytes, tables {len(blob)} bytes, offsets {offs}')


if __name__ == '__main__':
    main()
