"""Tables and constants of the fixed-point module awb2.c, generated from the trained parameters (model.py) and golden.py."""
import math
import numpy as np
import model, golden

FQ_TARGET = 30
E_LO, E_HI = -1536, 3328                     # clamp of the scene brightness (8.8 EV)
KR, KB = 0.6313, 0.3313                      # gain units at unity capture words: gain = K * 8192 / (raw R/G)   [to re-check on the camera]


def build():
    p = model.params()
    Ff = p['Ff']                              # (2, 64, 64) complex
    fq = FQ_TARGET - int(math.ceil(math.log2(np.abs(np.concatenate([Ff.real.ravel(), Ff.imag.ravel()])).max() + 1e-12)))
    fq = min(fq, 30)
    ff = np.stack([np.round(Ff.real * 2 ** fq), np.round(Ff.imag * 2 ** fq)], -1).astype(np.int64)      # (2, 64, 64, 2)
    assert np.abs(ff).max() < 2 ** 31
    bias = np.round(p['B'] * 2 ** 14).astype(np.int64)
    assert bias.shape == (4, 64, 64)
    assert np.abs(bias).max() < 2 ** 31
    t = {}
    t['lnm'] = np.array([round(2 ** 24 * math.log(1 + i / 256)) for i in range(257)], dtype=np.uint32)
    t['ff'] = ff.reshape(-1).astype(np.int32)
    t['bias'] = bias.reshape(-1).astype(np.int32)
    t['tw'] = np.array([[round(2 ** 30 * math.cos(2 * math.pi * k / 64)), round(2 ** 30 * math.sin(2 * math.pi * k / 64))] for k in range(32)], dtype=np.int32).reshape(-1)
    es = np.arange(E_LO, E_HI + 17, 16)
    t['tanh'] = np.array([round(4096 * math.tanh(2 * (e / 256 - 4) / 4)) for e in es], dtype=np.int16)
    t['exp2n'] = np.array([round(2 ** 30 * 2 ** (-i / 256)) for i in range(257)], dtype=np.uint32)
    t['atan'] = np.array([round(math.atan(2.0 ** -i) / (2 * math.pi) * 2 ** 32) for i in range(28)], dtype=np.uint32)
    t['cs20'] = np.array([[round(2 ** 20 * math.cos(2 * math.pi * k / 64)), round(2 ** 20 * math.sin(2 * math.pi * k / 64))] for k in range(64)], dtype=np.int32).reshape(-1)
    t['rc'] = np.array([0] + [-(-2 ** 20 // n) for n in range(1, 9)], dtype=np.uint32)
    c = dict(FQ=fq, E_LO=E_LO, E_HI=E_HI, NTANH=len(es),
             V0Q24=round(model.V0 * 2 ** 24), U0Q24=round(model.U0 * 2 ** 24), U0Q16=round(model.U0 * 65536), V0Q16=round(model.V0 * 65536),
             LN2Q24=round(math.log(2) * 2 ** 24), INVLN2Q16=round(65536 / math.log(2)),
             X_ZERO_Q16=round(golden.X_ZERO * 65536), X_SPAN_INV_Q16=round(65536 / (golden.X_FULL - golden.X_ZERO)),
             RETK_AUTO=round(golden.RETAIN[golden.AUTO] * math.log(2) / 2 * 65536), RETK_WARM=round(golden.RETAIN[golden.WARM] * math.log(2) / 2 * 65536),
             RETK_WHITE=round(golden.RETAIN[golden.WHITE] * math.log(2) / 2 * 65536),
             KQ=round(golden.Q * 2 ** 32), R_MIN=round(golden.R_MIN * 2 ** 32), R_MAX=round(golden.R_MAX * 2 ** 32), GATE=int(golden.GATE),
             FAR_W=round(golden.STILL_FAR * math.log(2) * 65536), FAR_T=round(2 * golden.STILL_FAR * math.log(2) * 65536),
             CONF_SLACK=round(0.03 * 65536),
             CR_Q30=round(KR * model.STAT_F[0] * 2 ** 30), CB_Q30=round(KB * model.STAT_F[2] * 2 ** 30),
             VARK=round(2 * (64 / (2 * math.pi * 32)) ** 2 * 1024 * 256), PERIOD=4, MAGIC=0x32425741)
    return t, c


def header(c):
    return '/* GENERATED by tables.py -- do not edit. */\n' + ''.join(f'#define AWB2_{k} ({v})\n' for k, v in c.items())


if __name__ == '__main__':
    t, c = build()
    open('awb2_const.h', 'w').write(header(c))
    print(c); print({k: (v.dtype, v.shape) for k, v in t.items()})
