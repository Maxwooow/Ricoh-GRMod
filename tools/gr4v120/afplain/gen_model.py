"""Write core/src/fw/gr4v120/aspect/subjectaf-model-code.ts from the trained model file (the network of the camera builds).

  python3 tools/gr4v120/afplain/gen_model.py subject-n96.bin

The model is the integer network trained off the camera on public data sets (README.md; 96 x 64 input, 12 x 8 scores; 63960 bytes,
SHA-256 8d3291b4...). It names no firmware address: GR IV 1.21 uses the same file (core/overlays.mjs), so the 1.21 copy of
this script is not run. The model file itself is not kept in the repository (the generated file holds it, with its hash)."""
import base64, hashlib, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / 'core' / 'src' / 'fw' / 'gr4v120' / 'aspect' / 'subjectaf-model-code.ts'
FROZEN = '8d3291b4a804e20ab08e6e2d9b059430ea4be7b1aced4be8b3fb72e0b5b9217f'

data = Path(sys.argv[1]).read_bytes()
sha = hashlib.sha256(data).hexdigest()
if sha != FROZEN:
    raise SystemExit(f'model {sha} is not the one of the camera builds ({FROZEN})')
OUT.write_text(
    '// SPDX-License-Identifier: GPL-2.0-only\n'
    '// GENERATED by tools/gr4v120/afplain/gen_model.py from subject-n96.bin -- do not edit.\n'
    '// The subject network (tools/gr4v120/afplain/README.md); integer weights, read by runtime/subject_net.c.\n\n'
    f"export const SUBJECTAF_MODEL = '{base64.b64encode(data).decode()}';\n"
    f'export const SUBJECTAF_MODEL_LENGTH = {len(data)};\n'
    f"export const SUBJECTAF_MODEL_SHA256 = '{sha}';\n")
print(OUT.relative_to(ROOT), len(data), sha)
