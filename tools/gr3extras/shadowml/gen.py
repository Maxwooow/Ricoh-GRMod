"""Compile tools/gr3extras/shadowml/shadowml.c (GR III's learned Auto for Shadow Correction) and write
core/src/fw/gr3x/shadowml-code.ts.

The compiler, flags and checks are GR IV's (tools/gr4v120/shadowml/gen.py: position independent, linked at two addresses and
compared, no data sections, no undefined symbols, `shadowml` at offset 0), and so is the constants header
(tools/gr4v120/shadowml/shadowml_const.h, from ref.py). The model blob is not compiled here: GR III embeds GR IV's
(core/src/fw/gr4v120/aspect/shadowml-data.ts).

    python3 tools/gr3extras/shadowml/gen.py
"""
import base64
import hashlib
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
G4 = ROOT / 'tools/gr4v120/shadowml'
sys.path[:0] = [str(G4)]
import gen as g4gen  # noqa: E402  (GR IV's compiler set-up)
import ref  # noqa: E402

SRC = HERE / 'shadowml.c'
OUT = ROOT / 'core/src/fw/gr3x/shadowml-code.ts'


def main():
    g4gen.SRC = SRC                     # build() compiles g4gen.SRC with -I tools/gr4v120/shadowml (shadowml_const.h)
    cc, ld, objcopy = g4gen.tools()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        a = g4gen.build(cc, ld, objcopy, tmp, 0x10000)
        b = g4gen.build(cc, ld, objcopy, tmp, 0x54430000)
        su = g4gen.stack_usage(cc, tmp)
    if a != b:
        sys.exit('module is not position independent')
    while len(a) % 4:
        a += b'\0'
    version = g4gen.run(cc + ['--version']).splitlines()[0]
    src_hash = hashlib.sha256(SRC.read_bytes() + g4gen.HDR.read_bytes()).hexdigest()
    OUT.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/gr3extras/shadowml/gen.py from tools/gr3extras/shadowml/shadowml.c (+ tools/gr4v120/shadowml/shadowml_const.h) -- do not edit.\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256 (shadowml.c followed by shadowml_const.h): {src_hash}\n'
        '// Position independent: entry `shadowml(ctx, P, mode, hl, idx)` at offset 0; ctx layout in shadowml.c (struct shadowml_ctx).\n\n'
        f"export const GR3X_SHADOWML_CODE = '{base64.b64encode(a).decode()}';\n"
        f'export const GR3X_SHADOWML_CODE_LENGTH = {len(a)};\n'
        f'export const GR3X_SHADOWML_MAGIC = 0x{ref.MAGIC:08x};\n'
        f"export const GR3X_SHADOWML_SOURCE_SHA256 = '{src_hash}';\n")
    print(f'{OUT}: {len(a)} bytes')
    print('stack usage per function (bytes):', su)


if __name__ == '__main__':
    main()
