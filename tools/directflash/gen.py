"""Compile tools/directflash/directflash.c and write core/src/fw/aspect/directflash-code.ts.

Like the date imprint module (tools/datestamp/gen.py): position independent (-fropi -frwpi, no global
data), linked at two addresses and compared. Unlike it, the module uses the floating-point unit: it
is built for the hard-float ABI (VFPv3, as the camera's own code), because the values it works on and
the camera function it calls (0x536792E0, Av in s0, Tv back in s0) are floats. No library: every
operation must be a VFP instruction; the build fails if anything is left undefined.
Compiler: clang if present, else `python3 -m ziglang cc` (GRMOD_ZIG=1 forces it).
"""
import base64
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = HERE / 'directflash.c'
OUT = ROOT / 'core' / 'src' / 'fw' / 'aspect' / 'directflash-code.ts'
ENTRY = 'df_plan'
USE_ZIG = bool(os.environ.get('GRMOD_ZIG')) or not (shutil.which('clang') and shutil.which('ld.lld') and shutil.which('llvm-objcopy'))
FLAGS = ['-mcpu=cortex_a9' if USE_ZIG else '-mcpu=cortex-a9', '-marm', '-mfloat-abi=hard', '-mfpu=vfpv3', '-Os',
         '-ffreestanding', '-fno-builtin', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables', '-nostdlib',
         '-fropi', '-frwpi', '-fno-jump-tables', '-Wall', '-Wextra', '-Werror']


def tools():
    if not USE_ZIG:
        return ['clang', '-target', 'armv7-none-eabihf'], ['ld.lld'], ['llvm-objcopy']
    z = [sys.executable, '-m', 'ziglang']
    return z + ['cc', '-target', 'arm-freestanding-eabihf'], z + ['ld.lld'], z + ['objcopy']


def run(cmd):
    r = subprocess.run([str(c) for c in cmd], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'{" ".join(map(str, cmd))}\n{r.stdout}{r.stderr}')
    return r.stdout


def build(cc, ld, objcopy, tmp, origin, extra=()):
    obj = tmp / 'df.o'
    run(cc + FLAGS + list(extra) + ['-c', SRC, '-o', obj])
    undefined = [l for l in run(['readelf', '-s', '-W', obj]).splitlines() if ' UND ' in l and l.split()[-1] != 'UND' and not l.strip().endswith(': 0')]
    names = [l.split()[-1] for l in undefined if len(l.split()) >= 8]
    if names:
        sys.exit(f'module needs symbols from a library: {names}')
    elf = tmp / f'df_{origin:x}.elf'
    run(ld + [f'-Ttext=0x{origin:x}', f'--entry={ENTRY}', '-o', elf, obj])
    out = tmp / f'df_{origin:x}.bin'
    run(objcopy + ['-O', 'binary', '-j', '.text', elf, out])
    sections = run(['readelf', '-S', '-W', elf])
    for name in ('.data', '.bss', '.rodata', '.got'):
        if f' {name} ' in sections or f' {name}.' in sections:
            sys.exit(f'module has a {name} section')
    symbols = run(['readelf', '-s', '-W', elf])
    entry = [l for l in symbols.splitlines() if l.strip().endswith(f' {ENTRY}')]
    if not entry:
        sys.exit(f'no {ENTRY}')
    return out.read_bytes(), int(entry[0].split()[1], 16) - origin


def main():
    cc, ld, objcopy = tools()
    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        a, ea = build(cc, ld, objcopy, tmp, 0x10000)
        b, eb = build(cc, ld, objcopy, tmp, 0x543f0000)
        da, dea = build(cc, ld, objcopy, tmp, 0x10000, ['-DDIAG'])
        db, deb = build(cc, ld, objcopy, tmp, 0x543f0000, ['-DDIAG'])
    if a != b or ea != eb or da != db or dea != deb:
        sys.exit('module is not position independent')
    while len(a) % 4:
        a += b'\0'
    while len(da) % 4:
        da += b'\0'
    version = run(cc + ['--version']).splitlines()[0]
    src_hash = hashlib.sha256(SRC.read_bytes()).hexdigest()
    OUT.write_text(
        '// SPDX-License-Identifier: GPL-2.0-only\n'
        '// GENERATED by tools/directflash/gen.py from tools/directflash/directflash.c -- do not edit.\n'
        f'// Compiler: {version}\n'
        f'// Source SHA-256: {src_hash}\n'
        f'// Position independent, hard-float ABI: entry `df_plan(ae, ctx)` at offset {ea}.\n\n'
        f"export const DIRECTFLASH_CODE = '{base64.b64encode(a).decode()}';\n"
        f'export const DIRECTFLASH_CODE_LENGTH = {len(a)};\n'
        f'export const DIRECTFLASH_ENTRY = {ea};\n'
        '/** Test builds only (-DDIAG): also leaves what each call saw in a buffer (see directflash.c). */\n'
        f"export const DIRECTFLASH_DIAG_CODE = '{base64.b64encode(da).decode()}';\n"
        f'export const DIRECTFLASH_DIAG_ENTRY = {dea};\n'
        f"export const DIRECTFLASH_SOURCE_SHA256 = '{src_hash}';\n")
    print(f'{OUT}: {len(a)} bytes, entry at {ea}')


if __name__ == '__main__':
    main()
