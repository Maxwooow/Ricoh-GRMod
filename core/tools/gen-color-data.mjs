// Generates core/src/color/data.ts from the private reference export (color_ref.json).
//
//   node core/tools/gen-color-data.mjs [path/to/color_ref.json] [--digits=5]
//
// The embedded numbers are measurements of one camera (base tone curve, 1026 paired colours
// "camera Standard" vs "Adobe Standard", fitted Adobe Standard base tone curve). No preset data.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const digitsArg = args.find((a) => a.startsWith('--digits='));
const digits = digitsArg ? Number(digitsArg.slice(9)) : 5;
const src = resolve(args.find((a) => !a.startsWith('--')) ?? resolve(here, '../testdata/private/color_ref.json'));
const dst = resolve(here, '../src/color/data.ts');

const ref = JSON.parse(readFileSync(src, 'utf8'));
const check = (cond, msg) => { if (!cond) { console.error('gen-color-data: ' + msg); process.exit(1); } };

const base = ref.base_curve;
check(Array.isArray(base) && base.length === 256, 'base_curve must have 256 entries');
check(base.every((v) => Number.isInteger(v) && v >= 0 && v <= 65535), 'base_curve entries must be uint16');
const cam = ref.cal_cam, adobe = ref.cal_adobe;
check(Array.isArray(cam) && Array.isArray(adobe) && cam.length === adobe.length && cam.length > 0, 'cal_cam / cal_adobe must be paired');
check(cam.every((r) => r.length === 3) && adobe.every((r) => r.length === 3), 'calibration rows must be RGB triples');
const tone = ref.tone_params;
check(Array.isArray(tone) && tone.length === 9 && tone.every(Number.isFinite), 'tone_params must be 9 finite numbers');

const num = (v) => {
  check(Number.isFinite(v) && v >= 0 && v <= 1, 'calibration value out of range: ' + v);
  let s = v.toFixed(digits);
  if (s.includes('.')) s = s.replace(/0+$/, '').replace(/\.$/, '');
  if (s.startsWith('0.')) s = s.slice(1);
  return s === '' ? '0' : s;
};
const wrap = (items, perLine) => {
  const lines = [];
  for (let i = 0; i < items.length; i += perLine) lines.push('  ' + items.slice(i, i + perLine).join(',') + ',');
  return lines.join('\n');
};
const triples = (rows) => wrap(rows.map((r) => r.map(num).join(',')), 6);

const out = `// GENERATED by core/tools/gen-color-data.mjs from color_ref.json. Do not edit by hand.
// Measurements of the GR IV colour pipeline (no preset data):
//   BASE_CURVE  camera base tone curve, 256 entries, value/16383 = display for linear input i/256
//   CAL_CAM     ${cam.length} colours as rendered by the camera's own "Standard" Image Control (sRGB-encoded 0..1)
//   CAL_ADOBE   the same scene colours as rendered by Lightroom "Adobe Standard" (sRGB-encoded 0..1)
//   TONE_PARAMS parameters of the Adobe Standard base tone curve model (see look.ts, class Tone)
// Calibration pairs are rounded to ${digits} decimals.

export const CAL_COUNT = ${cam.length};

export const BASE_CURVE = new Uint16Array([
${wrap(base.map(String), 16)}
]);

export const CAL_CAM = new Float32Array([
${triples(cam)}
]);

export const CAL_ADOBE = new Float32Array([
${triples(adobe)}
]);

export const TONE_PARAMS: number[] = [
${tone.map((v) => '  ' + String(v) + ',').join('\n')}
];
`;
writeFileSync(dst, out);
console.log(`wrote ${dst} (${out.length} bytes, ${cam.length} calibration pairs, ${digits} decimals)`);
